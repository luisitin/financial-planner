# tools/extract-shiller.py -- read Robert Shiller's monthly market data (vendor/data/shiller-ie_data.xls,
# free for research/personal use with attribution) into yearly returns for the years BEFORE Damodaran's
# table starts (1871-1927), so the backtest and risk pages can reach back to 1871:
#   modules/investments/backtest/data/shiller.js  ->  EARLY = [{ year, stocks, bonds, bills, inflation }]
# stocks = S&P composite, January to January, with the year's dividends added (D is the annualised
# dividend; a twelfth per month); bonds = a 10-year bond bought at January's GS10 yield and sold a year
# later at the next January's yield (coupon plus price change, 9 years left); bills = the January GS10
# yield as a stand-in (no short-rate series in the file; short paper paid about the long rate then);
# inflation = January-to-January CPI. 1928 on comes from Damodaran (tools/extract-history.py).
#   python tools/extract-shiller.py          (needs: pip install xlrd)
import os, json
import xlrd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
wb = xlrd.open_workbook(os.path.join(ROOT, "vendor", "data", "shiller-ie_data.xls"))
sh = wb.sheet_by_name("Data")
hdr = next(r for r in range(sh.nrows) if str(sh.cell_value(r, 0)).strip() == "Date")
rows = {}
for r in range(hdr + 1, sh.nrows):
    d = sh.cell_value(r, 0)
    if not isinstance(d, float):
        continue
    # 1871.1 is October (the sheet writes 1871.10 as 1871.1)
    s = f"{d:.2f}"
    year, month = int(s[:4]), int(s[5:7])
    rows[(year, month)] = {"p": sh.cell_value(r, 1), "d": sh.cell_value(r, 2), "cpi": sh.cell_value(r, 4), "gs10": sh.cell_value(r, 6)}

def num(v):
    return float(v) if isinstance(v, (int, float)) and v != "" else None

out = []
for y in range(1871, 1928):
    a, b = rows.get((y, 1)), rows.get((y + 1, 1))
    if not a or not b:
        continue
    p0, p1 = num(a["p"]), num(b["p"])
    divs = sum((num(rows[(y, m)]["d"]) or 0) / 12 for m in range(1, 13) if (y, m) in rows)
    stocks = (p1 + divs) / p0 - 1
    y0, y1 = num(a["gs10"]) / 100, num(b["gs10"]) / 100
    price1 = y0 / y1 * (1 - (1 + y1) ** -9) + (1 + y1) ** -9   # a par bond with coupon y0, 9 years left, priced at y1
    bonds = y0 + price1 - 1
    inflation = num(b["cpi"]) / num(a["cpi"]) - 1
    out.append({"year": y, "stocks": round(stocks, 6), "bonds": round(bonds, 6), "bills": round(y0, 6), "inflation": round(inflation, 6)})

path = os.path.join(ROOT, "modules", "investments", "backtest", "data", "shiller.js")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/extract-shiller.py from vendor/data/shiller-ie_data.xls (Robert Shiller, Yale;\n")
    f.write("// free with attribution). Do not edit by hand. Yearly returns 1871-1927, January to January:\n")
    f.write("// stocks = S&P composite price change plus the year's dividends; bonds = a 10-year bond bought at\n")
    f.write("// January's yield and sold a year later (coupon plus price change); bills = the January 10-year yield\n")
    f.write("// as a stand-in for short rates (approximate); inflation = CPI. Damodaran's table takes over in 1928.\n")
    f.write("export const EARLY = [\n")
    for row in out:
        f.write("  " + json.dumps(row) + ",\n")
    f.write("];\n")
print("wrote", path, len(out), "years", out[0]["year"], "to", out[-1]["year"])
