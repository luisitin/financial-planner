# tools/extract-history.py -- read Damodaran's yearly returns (vendor/data/damodaran-histretSP.xls,
# NYU Stern, free for any use with attribution) into a JS table the app can import:
#   modules/retirement/historical/data/returns.js  ->  [{ year, stocks, bonds, bills, inflation }]
# stocks = S&P 500 total return (dividends included), bonds = 10-year US Treasury total return,
# bills = 3-month T-bill, inflation = CPI change. Re-run after refreshing the xls (tools/fetch-vendor.mjs).
#   python tools/extract-history.py          (needs: pip install xlrd)
import os, json
import xlrd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
wb = xlrd.open_workbook(os.path.join(ROOT, "vendor", "data", "damodaran-histretSP.xls"))
ret = wb.sheet_by_name("Returns by year")
infl = wb.sheet_by_name("Inflation Rate")

# header row: "Year", "S&P 500 (includes dividends)", "US Small cap", "3-month T.Bill", "US T. Bond (10-year)", ...
hdr = next(r for r in range(ret.nrows) if str(ret.cell_value(r, 0)).strip() == "Year")
years = {}
for r in range(hdr + 1, ret.nrows):
    y = ret.cell_value(r, 0)
    if not isinstance(y, float) or y < 1900:
        break
    years[int(y)] = {"year": int(y), "stocks": round(float(ret.cell_value(r, 1)), 6), "bills": round(float(ret.cell_value(r, 3)), 6), "bonds": round(float(ret.cell_value(r, 4)), 6)}

# inflation sheet (a FRED export): "observation_date" | CPI change in percent | as a fraction
ih = next(r for r in range(infl.nrows) if str(infl.cell_value(r, 0)).strip() == "observation_date")
for r in range(ih + 1, infl.nrows):
    y = infl.cell_value(r, 0)
    if not isinstance(y, float):
        continue
    v = infl.cell_value(r, 2)
    if int(y) in years and isinstance(v, float):
        years[int(y)]["inflation"] = round(v, 6)

rows = [years[y] for y in sorted(years) if "inflation" in years[y]]
out = os.path.join(ROOT, "modules", "retirement", "historical", "data", "returns.js")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/extract-history.py from vendor/data/damodaran-histretSP.xls (Aswath Damodaran,\n")
    f.write("// NYU Stern, 'Historical Returns on Stocks, Bonds and Bills', free with attribution). Do not edit by hand.\n")
    f.write("// stocks: S&P 500 total return with dividends; bonds: 10-year US Treasury total return; bills: 3-month\n")
    f.write("// T-bill; inflation: CPI. Yearly, %d-%d.\n" % (rows[0]["year"], rows[-1]["year"]))
    f.write("export const RETURNS = [\n")
    for r in rows:
        f.write("  " + json.dumps(r, separators=(", ", ": ")) + ",\n")
    f.write("];\n")
print("wrote", out, len(rows), "years", rows[0]["year"], "-", rows[-1]["year"])
