// tools/gen-registry.mjs -- writes modules/registry.js from the folder tree.
// A module is any modules/<group>/<id>/module.js. Folders starting with "_" are
// skipped (that is where _template lives). Never edit registry.js by hand.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GROUPS } from "../core/groups.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MODS = path.join(ROOT, "modules");
const known = new Set(GROUPS.map((g) => g.id));
const entries = [];
const problems = [];
for (const group of fs.readdirSync(MODS, { withFileTypes: true })) {
  if (!group.isDirectory() || group.name.startsWith("_")) continue;
  if (!known.has(group.name)) { problems.push(`modules/${group.name}/ is not a group in core/groups.js`); continue; }
  for (const mod of fs.readdirSync(path.join(MODS, group.name), { withFileTypes: true })) {
    if (!mod.isDirectory() || mod.name.startsWith("_")) continue;
    const dir = path.join(MODS, group.name, mod.name);
    if (!fs.existsSync(path.join(dir, "module.js"))) { problems.push(`modules/${group.name}/${mod.name}/ has no module.js`); continue; }
    if (!/^[a-z0-9-]+$/.test(mod.name)) { problems.push(`modules/${group.name}/${mod.name}: folder names are kebab-case`); continue; }
    for (const f of ["README.md", "compute.js"]) if (!fs.existsSync(path.join(dir, f))) problems.push(`modules/${group.name}/${mod.name}/ is missing ${f}`);
    entries.push({ group: group.name, id: mod.name });
  }
}
entries.sort((a, b) => a.group.localeCompare(b.group) || a.id.localeCompare(b.id));
const out = [
  "// GENERATED by tools/gen-registry.mjs -- do not edit. Run `npm run registry`.",
  "// One entry per modules/<group>/<id>/module.js. Order in the sidebar comes from",
  "// core/groups.js and each module's `order`, not from this list.",
  "export default [",
  ...entries.map((e) => `  { group: ${JSON.stringify(e.group)}, id: ${JSON.stringify(e.id)}, load: () => import("./${e.group}/${e.id}/module.js") },`),
  "];",
  "",
].join("\n");
fs.writeFileSync(path.join(MODS, "registry.js"), out, "utf8");
console.log(`registry: ${entries.length} module(s)`);
for (const p of problems) console.log("  WARN " + p);
if (problems.length && process.argv.includes("--strict")) process.exit(1);
