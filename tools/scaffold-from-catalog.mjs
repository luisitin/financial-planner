// tools/scaffold-from-catalog.mjs -- create a placeholder module for every page listed in
// docs/MODULE_CATALOG.md that has no folder yet, so the whole app is visible as
// "Coming soon" pages before anything is built.
//
//   node tools/scaffold-from-catalog.mjs            create missing placeholders
//   node tools/scaffold-from-catalog.mjs --dry-run  just list what would be created
//
// Never touches an existing folder. A placeholder's module.js has status: "planned" and
// placeholder: true; its view renders core/ui/placeholder.js. To build the page for real,
// replace the folder's files (AGENTS.md "Promote a placeholder").
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GROUPS } from "../core/groups.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dry = process.argv.includes("--dry-run");
const catalog = fs.readFileSync(path.join(ROOT, "docs", "MODULE_CATALOG.md"), "utf8");
const icons = Object.fromEntries(GROUPS.map((g) => [g.id, g.icon]));
const rowRe = /^\| `([a-z0-9-]+)\/([a-z0-9-]+)` \| (.*?) \| (.*?) \| (\d+) \| (.*?) \| (.*?) \|\s*$/;
const perGroup = {};
let created = 0, skipped = 0, problems = 0;
const q = (s) => JSON.stringify(String(s ?? "").trim());

for (const line of catalog.split(/\r?\n/)) {
  const m = rowRe.exec(line);
  if (!m) continue;
  const [, group, id, title, status, phase, purpose, seeds] = m;
  perGroup[group] = (perGroup[group] ?? 0) + 1;
  const order = perGroup[group] * 10;
  if (!icons[group]) { console.log(`  WARN ${group}/${id}: group not in core/groups.js`); problems++; continue; }
  const dir = path.join(ROOT, "modules", group, id);
  if (fs.existsSync(dir)) { skipped++; continue; }
  created++;
  if (dry) { console.log(`  would create ${group}/${id}  "${title}"`); continue; }
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "module.js"), `// PLACEHOLDER generated by tools/scaffold-from-catalog.mjs from docs/MODULE_CATALOG.md.
// To build this page: keep id/group/title, replace compute.js/view.js/README.md with real
// ones (copy from modules/_template), set status to "stub" or "usable" and remove
// placeholder. See AGENTS.md "Promote a placeholder".
import { compute } from "./compute.js";
import { render } from "./view.js";

export default {
  id: ${q(id)},
  group: ${q(group)},
  title: ${q(title)},
  icon: ${q(icons[group])},
  order: ${order},
  version: 0,
  status: "planned",
  phase: ${Number(phase)},
  placeholder: true,
  enabledByDefault: true,
  needs: [],
  writes: [],
  heavy: false,
  purpose: ${q(purpose)},
  seeds: ${q(seeds)},
  compute,
  render,
};
`);
  fs.writeFileSync(path.join(dir, "compute.js"), `// PLACEHOLDER -- nothing to compute yet. Replace when building the page.
export function compute() { return { placeholder: true }; }
`);
  fs.writeFileSync(path.join(dir, "view.js"), `// PLACEHOLDER -- renders the shared "Coming soon" page. Replace when building the page.
import { renderPlaceholder } from "../../../core/ui/placeholder.js";
export function render(root, ctx) { return renderPlaceholder(root, ctx); }
`);
  fs.writeFileSync(path.join(dir, "README.md"), `# ${title}  (\`${group}/${id}\`)

**Status:** planned (placeholder page), phase ${phase}
**Purpose:** ${purpose}

## Inputs
To be decided when the page is built. Check \`plan.pageNotes["${group}/${id}"]\` for the owner's notes.

## Outputs
To be decided.

## Formulas
To be decided. Starting point: ${seeds}.

## Edge cases
-

## Tests
None yet (add module.test.mjs when compute() exists).

## Ideas / not yet
- Everything.
`);
}
console.log(`${dry ? "would create" : "created"} ${created} placeholder(s), ${skipped} page(s) already had a folder${problems ? `, ${problems} problem(s)` : ""}`);
if (!dry && created) console.log("now run: npm run registry && npm test && npm run check");
